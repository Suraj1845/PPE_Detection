"""Fine-tune D-FINE on the prepared PPE dataset (one GPU, Windows or Linux).

    python training\\train.py --variant s                   # D-FINE-S, 100 epochs, batch 8 (fits 12 GB)
    python training\\train.py --variant s --epochs 150
    python training\\train.py --variant s --resume          # continue after an interruption

What it does:

1. Writes ``training\\work\\dfine_<variant>_ppe.yml``: D-FINE's own custom-dataset config for that
   variant, pointed at ``training\\work\\data`` with your class count, epoch count and batch size.
   Learning rates are scaled linearly from D-FINE's batch size (64 for S, 128 for N) to yours.
2. Starts from the audited COCO weights in ``training\\weights`` (``-t``, D-FINE's fine-tuning mode:
   everything is reused except the class-specific heads, which start fresh).
3. Runs D-FINE's ``train.py`` as a single process (no torchrun), with mixed precision on the GPU.
   It evaluates on the validation split every epoch and keeps the best checkpoints as
   ``best_stg1.pth`` / ``best_stg2.pth`` in ``training\\work\\runs\\dfine_<variant>_ppe``.
4. Prints the export command for the best checkpoint.

Strong augmentation (zoom, crop, colour) stops for the last 10 % of epochs, mirroring D-FINE's
own schedule (200 of 220 epochs). Training curves: ``tensorboard --logdir training\\work\\runs``.
"""

from __future__ import annotations

import argparse
import copy
import json
import subprocess
import sys
from pathlib import Path

TRAINING = Path(__file__).resolve().parent
PROJECT = TRAINING.parent
DFINE = TRAINING / "D-FINE"
WORK = TRAINING / "work"
BASE_BATCH = {"n": 128, "s": 64}  # total_batch_size in D-FINE's custom configs


def scale_optimizer(optimizer: dict, factor: float) -> dict:
    scaled = copy.deepcopy(optimizer)
    if "lr" in scaled:
        scaled["lr"] = float(scaled["lr"]) * factor
    for group in scaled.get("params", []):
        if "lr" in group:
            group["lr"] = float(group["lr"]) * factor
    return scaled


def build_config(args: argparse.Namespace, data: Path) -> tuple[Path, Path]:
    import yaml

    names = json.loads((data / "labels.json").read_text(encoding="utf-8"))
    info = json.loads((data / "dataset_info.json").read_text(encoding="utf-8"))
    folders = info["image_folders"]
    base_config = DFINE / "configs" / "dfine" / "custom" / f"dfine_hgnetv2_{args.variant}_custom.yml"
    variant_yaml = yaml.safe_load(base_config.read_text(encoding="utf-8"))
    factor = args.batch / BASE_BATCH[args.variant] if args.lr_scale else 1.0
    stop = max(1, args.epochs - max(1, args.epochs // 10))
    output_dir = WORK / "runs" / f"dfine_{args.variant}_ppe"

    config = {
        "__include__": [str(base_config)],
        "num_classes": len(names),
        "remap_mscoco_category": False,
        "epochs": args.epochs,
        "output_dir": str(output_dir),
        "optimizer": scale_optimizer(variant_yaml["optimizer"], factor),
        "train_dataloader": {
            "total_batch_size": args.batch,
            "num_workers": args.workers,
            "dataset": {
                "img_folder": folders["train"],
                "ann_file": str(data / "train.json"),
                "transforms": {"policy": {"epoch": stop}},
            },
            "collate_fn": {"stop_epoch": stop},
        },
        "val_dataloader": {
            "total_batch_size": args.batch * 2,
            "num_workers": args.workers,
            "dataset": {"img_folder": folders["val"], "ann_file": str(data / "val.json")},
        },
    }
    WORK.mkdir(parents=True, exist_ok=True)
    config_path = WORK / f"dfine_{args.variant}_ppe.yml"
    config_path.write_text(
        "# Generated by training/train.py - edit the command-line options instead of this file.\n"
        + yaml.safe_dump(config, sort_keys=False),
        encoding="utf-8",
    )
    print(f"Config: {config_path}")
    print(f"  {len(names)} classes, {args.epochs} epochs (strong augmentation until epoch {stop}), batch {args.batch}, "
          f"learning rates x{factor:.4g}, {args.workers} data workers")
    return config_path, output_dir


def sample_images(data: Path, count: int) -> list[Path]:
    """The first ``count`` images of the test split (or validation split) that contain boxes."""
    info = json.loads((data / "dataset_info.json").read_text(encoding="utf-8"))
    split = "test" if (data / "test.json").is_file() else "val"
    coco = json.loads((data / f"{split}.json").read_text(encoding="utf-8"))
    with_boxes = {a["image_id"] for a in coco["annotations"]}
    folder = Path(info["image_folders"][split])
    return [folder / img["file_name"] for img in coco["images"] if img["id"] in with_boxes][:count]


def best_checkpoint(output_dir: Path) -> Path | None:
    for name in ("best_stg2.pth", "best_stg1.pth", "last.pth"):
        if (output_dir / name).is_file():
            return output_dir / name
    return None


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--variant", choices=sorted(BASE_BATCH), default="s", help="D-FINE size (default: s)")
    parser.add_argument("--data", type=Path, default=WORK / "data", help="output of prepare_dataset.py")
    parser.add_argument("--epochs", type=int, default=100)
    parser.add_argument("--batch", type=int, default=8, help="images per step (default 8 fits a 12 GB GPU)")
    parser.add_argument("--workers", type=int, default=4, help="data-loading processes (0 = load in the main process)")
    parser.add_argument("--device", default="cuda", help="cuda (default), cuda:1, or cpu (only for testing)")
    parser.add_argument("--no-lr-scale", dest="lr_scale", action="store_false", help="keep D-FINE's learning rates")
    parser.add_argument("--resume", action="store_true", help="continue from last.pth in the run folder")
    args = parser.parse_args(argv)

    if not (DFINE / "train.py").is_file():
        raise SystemExit("D-FINE is not set up yet: run  python training\\setup_dfine.py")
    data = args.data.resolve()
    if not (data / "labels.json").is_file():
        raise SystemExit(f"No prepared dataset in {data}: run  python training\\prepare_dataset.py --dataset <folder>")
    if args.epochs < 2 or args.batch < 1:
        raise SystemExit("--epochs must be at least 2 and --batch at least 1.")

    import torch

    if args.device.startswith("cuda"):
        if not torch.cuda.is_available():
            raise SystemExit(
                f"PyTorch {torch.__version__} sees no CUDA GPU. Install the training requirements with the CUDA "
                "index (training\\README.md), update the NVIDIA driver, or use --device cpu only for a test run."
            )
        print(f"GPU: {torch.cuda.get_device_name(0)}, PyTorch {torch.__version__}, CUDA {torch.version.cuda}")

    config_path, output_dir = build_config(args, data)
    command = [sys.executable, "train.py", "-c", str(config_path), "--seed", "0", "-d", args.device]
    if args.device.startswith("cuda"):
        command.append("--use-amp")
    if args.resume:
        last = output_dir / "last.pth"
        if not last.is_file():
            raise SystemExit(f"Nothing to resume: {last} does not exist.")
        command += ["-r", str(last)]
    else:
        weights = TRAINING / "weights" / f"dfine_{args.variant}_coco.pth"
        if not weights.is_file():
            raise SystemExit(f"{weights} is missing: run  python training\\setup_dfine.py")
        command += ["-t", str(weights)]
    print("Running:", " ".join(command), "\n", flush=True)
    result = subprocess.run(command, cwd=DFINE, check=False)
    if result.returncode != 0:
        print(f"\nTraining stopped with exit code {result.returncode}. To continue: python training\\train.py "
              f"--variant {args.variant} --resume")
        return result.returncode

    best = best_checkpoint(output_dir)
    if best is None:
        raise SystemExit(f"Training finished but no checkpoint was found in {output_dir}.")
    model_out = PROJECT / "models" / f"dfine_{args.variant}_ppe.onnx"
    verify = " ".join(f'--verify-image "{path}"' for path in sample_images(data, 2))
    print(f"\nBest checkpoint: {best}\nNext, export it (runs the ONNX parity checks on two test images):")
    print(f'  python scripts\\export_dfine_onnx.py --dfine-repo training\\D-FINE --config "{config_path}" '
          f'--checkpoint "{best}" --labels-json "{data / "labels.json"}" --output "{model_out}" {verify}')
    print(f"Then evaluate it:\n  python training\\evaluate_onnx.py --model {model_out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
